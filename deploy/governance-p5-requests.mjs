/** P5-03真实接口浏览器检查；只读取隔离夹具身份，不替换请求或响应。 */
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
const { chromium, expect } = createRequire(import.meta.url)(process.env.P5_PLAYWRIGHT_MODULE)
const root = process.env.P5_UI_FIXTURE, fixture = JSON.parse(fs.readFileSync(path.join(root, 'fixture.json'), 'utf8'))
const origin = 'http://127.0.0.1:15275', checks = [], browser = await chromium.launch({ headless: true })
const HTTP_OK = 200, HTTP_FORBIDDEN = 403
const passed = check => checks.push({ check, result: 'PASS' })
const select = (p, name) => p.locator('.ant-select').filter({ has: p.getByRole('combobox', { name, exact: true }) }).click()
const url = (route, tenant) => `${origin}/governance/${route}?tenant=${tenant}&application=commerce&environment=test`
async function page(token) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const profile = JSON.parse(Buffer.from(token.split('.')[1], 'base64url').toString())
  await context.addInitScript(({ key, value }) => sessionStorage.setItem(key, value), { key: `oidc.user:${process.env.VITE_CASDOOR_AUTHORITY}:${process.env.VITE_CASDOOR_CLIENT_ID}`, value: JSON.stringify({ access_token: token, token_type: 'Bearer', scope: 'openid', profile, expires_at: profile.exp }) })
  return context.newPage()
}
async function shot(p, name) {
  const drawer = p.locator('.ant-drawer-content-wrapper').last()
  if (await drawer.count()) await expect.poll(async () => { const box = await drawer.boundingBox(); return box ? Math.round(box.x + box.width) : -1 }).toBe(p.viewportSize().width)
  await p.screenshot({ path: path.join(root, name + '.png'), fullPage: true, animations: 'disabled' }) }
try {
  const admin = await page(fixture.manager_token), member = await page(fixture.member_token)
  await admin.goto(url('policies', fixture.tenants[0]))
  await admin.getByRole('button', { name: '创建申请策略', exact: true }).click()
  await select(admin, '策略固定角色版本'); await admin.getByTitle('temporary-exporter · v1', { exact: true }).click()
  await select(admin, '资源类型'); await admin.getByTitle('product', { exact: true }).click()
  await admin.getByLabel('范围标识', { exact: true }).fill('STORE-A')
  await select(admin, '审批成员'); await admin.getByTitle(`EMPLOYEE · ${fixture.owners[0]} · 第1代`, { exact: true }).click()
  await admin.getByLabel('最长授权分钟数', { exact: true }).fill('10')
  await admin.getByRole('button', { name: '登记固定策略', exact: true }).click()
  await expect(admin.getByRole('button', { name: '策略详情', exact: true })).toBeVisible()
  await admin.getByRole('button', { name: '策略详情', exact: true }).click()
  await expect(admin.getByText('指定门店：STORE-A', { exact: true })).toBeVisible()
  await shot(admin, 'policy-detail-1440'); await admin.keyboard.press('Escape')
  passed('manager registers immutable store-scoped export policy through real UI; details preserve role and scope')
  await member.goto(url('requests', fixture.tenants[0]))
  await member.getByRole('button', { name: '申请权限', exact: true }).click()
  await member.getByRole('button', { name: '提交申请', exact: true }).click()
  await expect(member.getByText('请选择可申请策略', { exact: true })).toBeVisible()
  await select(member, '可申请策略'); await member.getByTitle('temporary-exporter · v1 · 策略1', { exact: true }).click()
  await member.getByLabel('申请原因', { exact: true }).fill('指定门店商品核对，限时导出')
  await expect(member.locator('.ant-form-item-explain-error')).toHaveCount(0)
  await shot(member, 'request-form-1440')
  await member.getByRole('button', { name: '提交申请', exact: true }).click()
  await expect(member.getByText('实际状态：已提交，等待流程启动', { exact: true })).toBeVisible()
  const request = new URL(member.url()).searchParams.get('request')
  if (!request) throw new Error('request detail must survive URL refresh')
  await shot(member, 'request-detail-1440')
  await member.reload(); await expect(member.getByText('实际状态：已提交，等待流程启动', { exact: true })).toBeVisible()
  passed('partner submits real request, sees original scope and pending workflow, reload retains owned detail')
  const cross = await member.request.get(`${origin}/api/governance/v1/requests/${request}?tenant_id=${fixture.tenants[1]}&application_id=commerce&environment=test`, { headers: { Authorization: `Bearer ${fixture.member_token}` } })
  if (cross.status() !== HTTP_FORBIDDEN) throw new Error('cross tenant request detail must fail')
  const managerRead = await admin.request.get(`${origin}/api/governance/v1/requests/${request}?tenant_id=${fixture.tenants[0]}&application_id=commerce&environment=test`, { headers: { Authorization: `Bearer ${fixture.manager_token}` } })
  if (managerRead.status() !== HTTP_FORBIDDEN) throw new Error('management is not ownership of someone else request')
  passed('same-user cross-tenant replay and manager reading another beneficiary request both denied')
  await member.getByRole('button', { name: '取消申请 / 回收本来源', exact: true }).click()
  await member.getByRole('button', { name: '确认取消或回收', exact: true }).click()
  await expect(member.getByText('实际状态：已取消', { exact: true })).toBeVisible()
  await member.setViewportSize({ width: 390, height: 844 }); await shot(member, 'request-detail-390')
  passed('cancel uses original request and backend confirms cancelled; detail supports narrow viewport')
  await admin.goto(url('invitations', fixture.tenants[2]))
  await admin.getByRole('button', { name: '创建邀请', exact: true }).click()
  await admin.getByLabel('目标登录标识（精确 subject）', { exact: true }).fill(fixture.external_subject)
  await admin.getByLabel('邀请原因', { exact: true }).fill('门店合作邀请')
  await shot(admin, 'invitation-form-1440')
  const issued = admin.waitForResponse(r => r.url().endsWith('/portal-invitations') && r.request().method() === 'POST')
  await admin.getByRole('button', { name: '提交邀请', exact: true }).click()
  const response = await issued
  if (response.status() !== HTTP_OK) throw new Error('invitation issue failed')
  const command = response.request().postDataJSON(), result = await response.json()
  if ('token' in result || 'token_hash' in result) throw new Error('invitation response exposes proof')
  await expect(admin.getByText('邀请已创建，尚未建立业务授权', { exact: true })).toBeVisible()
  // 成功页有邀请证明，刻意不留截图/trace，只在内存传递给被邀请浏览器。
  await member.setViewportSize({ width: 1440, height: 1000 }); await member.goto(origin + '/invitations/accept')
  await member.getByLabel('邀请编号', { exact: true }).fill(result.id)
  await member.getByLabel('邀请证明', { exact: true }).fill(command.token)
  await member.getByRole('button', { name: '接受邀请', exact: true }).click()
  await expect(member.getByText('已加入邀请对应组织', { exact: true })).toBeVisible()
  await shot(member, 'invitation-accepted-1440')
  await member.goto(`${origin}/governance?tenant=${fixture.tenants[2]}`)
  await expect(member.getByText('当前没有关联应用', { exact: true })).toBeVisible()
  passed('explicit manager creates invitation; exact external user accepts; new membership has no implicit business grant')
  await admin.getByRole('button', { name: '关闭', exact: true }).click()
  await admin.getByRole('button', { name: '已保存，关闭', exact: true }).click()
  await admin.getByRole('button', { name: '创建邀请', exact: true }).click()
  await admin.getByLabel('目标登录标识（精确 subject）', { exact: true }).fill(fixture.external_subject)
  await admin.getByLabel('邀请原因', { exact: true }).fill('撤销路径验证')
  await admin.getByRole('button', { name: '提交邀请', exact: true }).click()
  await expect(admin.getByText('邀请已创建，尚未建立业务授权', { exact: true })).toBeVisible()
  await admin.getByRole('button', { name: '关闭', exact: true }).click()
  await admin.getByRole('button', { name: '已保存，关闭', exact: true }).click()
  await admin.getByRole('button', { name: '撤销邀请', exact: true }).click()
  await admin.getByLabel('撤销原因', { exact: true }).fill('合作取消')
  await admin.getByRole('button', { name: '确认撤销邀请', exact: true }).click()
  await expect(admin.getByText('已撤销', { exact: true })).toBeVisible()
  passed('manager revokes pending invitation through real UI without affecting accepted member')
  await member.goto(url('invitations', fixture.tenants[0]))
  await expect(member.getByText('当前没有外部邀请管理授权', { exact: true })).toBeVisible()
  passed('external cannot query invitation management even by direct route')
  fs.writeFileSync(path.join(root, 'requests-ui-result.json'), JSON.stringify(checks, null, 2))
} catch (failure) {
  // 不截含证明的任意失败页，避免凭据进入截图；调用栈也只包含固定标签。
  fs.writeFileSync(path.join(root, 'requests-ui-result.json'), JSON.stringify(checks, null, 2))
  throw failure
} finally { await browser.close() }
